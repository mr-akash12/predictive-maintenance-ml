"""Independent held-out evaluation; outputs measurable classification evidence."""
import argparse
import json
import joblib
import matplotlib
matplotlib.use('Agg')
import matplotlib.pyplot as plt
from sklearn.metrics import (precision_score, recall_score, f1_score, roc_auc_score,
                             average_precision_score, confusion_matrix, ConfusionMatrixDisplay,
                             RocCurveDisplay, PrecisionRecallDisplay)
from .config import MODEL_PATH, METRICS_PATH, FIGURES, FEATURES, create_output_dirs
from .data import load_data
from .features import split_data


def evaluate(model, x_test, y_test):
    scores = model.predict_proba(x_test)[:, 1]
    prediction = (scores >= 0.5).astype(int)
    cm = confusion_matrix(y_test, prediction, labels=[0, 1])
    output = {
        'threshold': 0.5, 'test_rows': int(len(y_test)),
        'positive_test_rows': int(y_test.sum()),
        'precision': float(precision_score(y_test, prediction, zero_division=0)),
        'recall': float(recall_score(y_test, prediction, zero_division=0)),
        'f1': float(f1_score(y_test, prediction, zero_division=0)),
        'roc_auc': float(roc_auc_score(y_test, scores)),
        'average_precision': float(average_precision_score(y_test, scores)),
        'confusion_matrix_rows_true_0_1_cols_pred_0_1': cm.tolist(),
        'false_negatives': int(cm[1, 0]), 'false_positives': int(cm[0, 1]),
        'input_features': FEATURES,
        'split_note': 'Stratified random hold-out, 20%, seed 42; synthetic AI4I data; no temporal validation.',
    }
    create_output_dirs()
    METRICS_PATH.write_text(json.dumps(output, indent=2), encoding='utf-8')
    ConfusionMatrixDisplay(confusion_matrix=cm, display_labels=[0, 1]).plot(cmap='Blues')
    plt.title('Held-out confusion matrix');plt.tight_layout()
    plt.savefig(FIGURES / 'confusion_matrix.png', dpi=160);plt.close()
    RocCurveDisplay.from_predictions(y_test, scores)
    plt.title('Held-out ROC curve');plt.tight_layout()
    plt.savefig(FIGURES / 'roc_curve.png', dpi=160);plt.close()
    PrecisionRecallDisplay.from_predictions(y_test, scores)
    plt.title('Held-out precision–recall curve');plt.tight_layout()
    plt.savefig(FIGURES / 'precision_recall_curve.png', dpi=160);plt.close()
    return output


def main():
    argparse.ArgumentParser().parse_args()
    if not MODEL_PATH.exists():
        raise FileNotFoundError(f'Model not found: {MODEL_PATH}. Run python -m src.train first.')
    model = joblib.load(MODEL_PATH)  # Load only models generated by trusted code.
    _, x_test, _, y_test = split_data(load_data())
    print(json.dumps(evaluate(model, x_test, y_test), indent=2))

if __name__ == '__main__':main()
